#!/usr/bin/env python3
"""Extract ladder volumes from PF2 BSPs for the nav mesh.

vbsp turns func_ladder brushes into ladder contents plus compile-time "info_ladder" records (mins/maxs)
in the entity lump. PF2's server has no info_ladder entity and TF2's offline nav generator ignores
them, so the shipped meshes have no ladders. The plugin reads this file at map load and creates
native CNavLadder objects (CNavMesh::CreateLadder).

  python -I ladders.py <maps-dir> <out.cfg>
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bspents import entities


def main():
    mapsdir, out = sys.argv[1], sys.argv[2]
    lines = ['// pf2-nextbot: ladder volumes per map (mins maxs), generated by tools/ladders.py from the BSPs.',
             '"PF2Ladders"', "{"]
    total = maps = 0
    for f in sorted(os.listdir(mapsdir)):
        if not f.lower().endswith(".bsp"):
            continue
        try:
            ents = entities(os.path.join(mapsdir, f))
        except Exception as e:
            print("skip", f, e)
            continue
        lads = []
        for e in ents:
            if e.get("classname") != "info_ladder":
                continue
            try:
                mn = [float(e["mins." + a]) for a in "xyz"]
                mx = [float(e["maxs." + a]) for a in "xyz"]
            except (KeyError, ValueError):
                continue
            lads.append(mn + mx)
        if not lads:
            continue
        maps += 1
        total += len(lads)
        lines.append('\t"%s"' % f[:-4])
        lines.append("\t{")
        for i, l in enumerate(lads):
            lines.append('\t\t"%d"\t"%s"' % (i, " ".join("%.0f" % v for v in l)))
        lines.append("\t}")
    lines.append("}")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%d ladders on %d maps -> %s" % (total, maps, out))


if __name__ == "__main__":
    main()
